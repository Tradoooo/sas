"""Amazon Quick stack: datasets and multi-tenant row-level security (lot 16).

Consumes the dataset bundle generated by ``sas.quicksight`` — the single source
of truth — so QuickSight never reinvents the schema of the 15 DynamoDB tables
and the RLS rules of EF-53 stay identical to the ones the tests assert.
"""

from __future__ import annotations

from typing import Any

from sas import quicksight


def datasets_quick() -> tuple[dict[str, Any], ...]:
    """The three datasets, from ``sas.quicksight`` (registre, dérive, coût)."""
    return tuple(quicksight.bundle()["datasets"])


def regles_rls_quick() -> tuple[dict[str, Any], ...]:
    """The multi-tenant RLS rules, from ``sas.quicksight`` (EF-53)."""
    return tuple(quicksight.bundle()["rls"])


def quick_cdk(scope: Any) -> Any:
    """Build the QuickSight datasets. ``aws_cdk`` imported here only."""
    import aws_cdk as cdk  # lazy on purpose

    for dataset in datasets_quick():
        cdk.CfnOutput(scope, f"dataset-{dataset['identifiant']}", value=dataset["nom"])
    cdk.Tags.of(scope).add("projet", "sas")
    return None
